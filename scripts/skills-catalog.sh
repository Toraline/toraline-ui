#!/usr/bin/env bash
# Builds docs/workflow/skills.md from the header of every skill in agent/skills.
# The catalog is generated. Never edit it by hand.
set -euo pipefail
root="$(git rev-parse --show-toplevel)"; cd "$root"
out="docs/workflow/skills.md"; mkdir -p "$(dirname "$out")"

field() { # field <file> <name>: first "name: value" line of the frontmatter
  awk -v n="$2" '
    NR==1 && $0!="---" { exit }
    NR>1 && $0=="---" { exit }
    { line=$0; sub(/^[ \t]+/, "", line) }
    index(line, n ": ")==1 { sub(/^[^:]+:[ \t]*/, "", line); print line; exit }
  ' "$1"
}

{
  echo "# Skill catalog"
  echo
  echo "Generated by \`make skills-catalog\` from the header of each skill in \`agent/skills/\`. Do not edit by hand."
  echo
  for pack in core team project; do
    rows=""
    for f in agent/skills/*/SKILL.md; do
      [ -f "$f" ] || continue
      p="$(field "$f" pack)"; [ -n "$p" ] || p="project"
      [ "$p" = "$pack" ] || continue
      name="$(field "$f" name)"; stage="$(field "$f" stage)"; desc="$(field "$f" description)"
      desc="${desc%%. *}."
      rows+="| \`/$name\` | ${stage:--} | ${desc//|/\\|} |"$'\n'
    done
    [ -n "$rows" ] || continue
    case "$pack" in
      core) echo "## Core skills" ;;
      team) echo "## Team pack (work with other people)" ;;
      project) echo "## Skills of this project only" ;;
    esac
    echo
    echo "| Skill | Stage | What it does |"
    echo "|---|---|---|"
    printf '%s' "$rows"
    echo
  done
} > "$out"
echo "Wrote $out"
